#!/usr/bin/env node
/**
 * Builds src/content/privacy-drafts.ts from the archived EN/DE privacy pages
 * (../source-assets/documents/page-text-archive/{en,de}_p_rodo.txt), verbatim, in the same
 * structure as src/content/privacy.ts.
 *
 *   node scripts/build-privacy-drafts.mjs
 *
 * These are HISTORICAL translations of the legacy site. They are not legally current
 * (no SH II controller, no website forms, old wording) and stay unpublished until the
 * client's legal review approves them (docs/client-confirmations.md C-35 / C-53).
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ARCHIVE = path.resolve(SITE, '..', 'source-assets', 'documents', 'page-text-archive');
const OUT = path.join(SITE, 'src', 'content', 'privacy-drafts.ts');
// Section order is the same in PL, EN and DE: slaughterhouse, cutting plant, sales, head office.
const ENTITY_ORDER = ['sh', 'cp', 'gmbh', 'centrala'];

function parse(text) {
  const lines = text.replace(/\r\n?/g, '\n').split('\n').map((l) => l.trim());
  const intro = [];
  const sections = [];
  let section = null;
  let item = null;
  let list = null;
  let heading = 0;
  const target = () => (item ? item.blocks : section ? null : intro);
  const push = (block) => {
    const t = target();
    if (t) t.push(block);
  };
  for (const raw of lines) {
    if (!raw || raw.startsWith('[IMG:')) {
      list = null;
      continue;
    }
    if (raw.startsWith('## ')) {
      heading += 1;
      list = null;
      item = null;
      if (heading === 1) continue; // page title
      section = { entity: ENTITY_ORDER[sections.length], title: raw.slice(3).trim(), items: [] };
      sections.push(section);
      continue;
    }
    if (heading === 0) continue; // header slogans before the page title
    const link = raw.match(/^\[A:javascript: void\(0\);\]\s*(.+)$/);
    if (link && section) {
      item = { title: link[1].trim(), blocks: [] };
      section.items.push(item);
      list = null;
      continue;
    }
    const clean = raw.replace(/\[A:mailto:[^\]]+\]\s*/g, '').replace(/\s+/g, ' ').trim();
    if (clean.startsWith('- ')) {
      if (!list) {
        list = { type: 'ul', items: [] };
        push(list);
      }
      list.items.push(clean.slice(2).trim());
    } else {
      list = null;
      push({ type: 'p', text: clean });
    }
  }
  if (sections.length !== ENTITY_ORDER.length) throw new Error(`expected ${ENTITY_ORDER.length} sections, got ${sections.length}`);
  return { intro, sections };
}

const out = {};
for (const lang of ['en', 'de']) out[lang] = parse(await readFile(path.join(ARCHIVE, `${lang}_p_rodo.txt`), 'utf8'));

const body = `/**
 * GENERATED by scripts/build-privacy-drafts.mjs — do not edit by hand.
 *
 * Historical EN/DE privacy translations from the legacy site, verbatim (including original
 * typos and the truncated sentences of the archive). NOT legally approved and NOT published:
 * the privacy page renders them only when \`privacyTranslationApproved[locale]\` in
 * src/content/privacy.ts is set to true after legal review (C-35, C-53). Until then EN/DE show
 * the authoritative Polish text and stay noindex.
 */
import type { PrivacyBlock, PrivacySection } from './privacy';

export const privacyDrafts: Record<'en' | 'de', { intro: PrivacyBlock[]; sections: PrivacySection[] }> = ${JSON.stringify(out, null, 2)};
`;
await writeFile(OUT, body);
console.log(`privacy drafts: en ${out.en.sections.length} sections, de ${out.de.sections.length} sections`);
